import argparse
import glob
import os
import shutil
import subprocess
import sys
import time

from common.config import CODE_DIR, DATA_DIR, RESULTS_DIR, FIGURES_DIR, DEFAULT_SLOTS, make_dirs
from common.safe_files import remove_file
from common.telemetry import reset_logs
from run_all import start_services, stop_services, port_in_use
from common.config import SERVICE_PORTS

# Runs the WHOLE project from scratch with one command, in order:
#
#   1. start the 4 services
#   2. generate the dataset (randomised scenarios)          generate_dataset.py
#   3. label every window with the 4 livelock conditions   labeling.py
#   4. train + evaluate the prediction model               prediction_model.py
#   5. build the service graph snapshots                   graph_builder.py
#   6. run the 5-strategy experiments                      experiment_arms.py
#   7. label the experiment runs too                       labeling.py --group experiment
#   8. check the data against queueing theory etc.         validate_data.py
#   9. draw all figures                                    make_figures.py
#  10. collect every number into results/RESULTS.md
#
#   python run_pipeline.py            full run (about 1.5 hours)
#   python run_pipeline.py --quick    small run for a demo (about 20 minutes)
#
# The previous results/ and data/ are copied to results_previous/ and
# data_previous/ first, so a quick demo run never destroys the full run.
#
# Every step writes its full output to results/logs/<step>.log.

LOG_DIR = os.path.join(RESULTS_DIR, "logs")


def run_step(number, title, script_args):
    print("[%2d] %-52s" % (number, title), end="", flush=True)
    started = time.time()
    log_path = os.path.join(LOG_DIR, "%02d_%s.log" % (number, script_args[0].replace(".py", "")))
    with open(log_path, "w") as log:
        result = subprocess.run([sys.executable] + script_args, cwd=CODE_DIR,
                                stdout=log, stderr=subprocess.STDOUT)
    seconds = time.time() - started
    if result.returncode != 0:
        print("FAILED after %.0fs -- see %s" % (seconds, log_path))
        return False
    print("done in %4.0fs" % seconds)
    return True


def back_up_previous():
    # never silently destroy an earlier full run: keep one backup copy
    if os.path.exists(os.path.join(RESULTS_DIR, "RESULTS.md")):
        backup = os.path.join(CODE_DIR, "results_previous")
        if os.path.exists(backup):
            shutil.rmtree(backup, ignore_errors=True)
        shutil.copytree(RESULTS_DIR, backup)
        print("previous results copied to results_previous/")
    if os.path.exists(DATA_DIR) and len(os.listdir(DATA_DIR)) > 0:
        backup = os.path.join(CODE_DIR, "data_previous")
        if os.path.exists(backup):
            shutil.rmtree(backup, ignore_errors=True)
        shutil.copytree(DATA_DIR, backup)
        print("previous data copied to data_previous/")


def clean_outputs():
    reset_logs()
    for name in ["labeled_windows*.csv", "baselines.json", "graph_snapshots.pkl", "retry_policy.json"]:
        for path in glob.glob(os.path.join(DATA_DIR, name)):
            remove_file(path)
    for path in glob.glob(os.path.join(RESULTS_DIR, "*.*")):
        if not path.endswith("calibration_report.txt"):
            remove_file(path)
    for path in glob.glob(os.path.join(FIGURES_DIR, "*.png")):
        remove_file(path)


def read_text(name):
    path = os.path.join(RESULTS_DIR, name)
    if not os.path.exists(path):
        return None
    with open(path, "r", encoding="utf-8") as f:
        return f.read().rstrip()


def write_results_md(settings):
    parts = []
    parts.append("# Results\n")
    parts.append("Generated by `run_pipeline.py` on %s. Settings: %s.\n"
                 % (time.strftime("%Y-%m-%d %H:%M"), settings))
    parts.append("Every number below comes from the files in `results/`, which the scripts write.")
    parts.append("Re-running the pipeline regenerates all of them.\n")

    sections = [
        ("1. Is the generated data trustworthy?", "data_validation.txt"),
        ("2. Testbed vs Alibaba production trace (optional)", "calibration_report.txt"),
        ("3. Livelock detection on the dataset", "labeling_dataset.txt"),
        ("4. Threshold sensitivity", "sensitivity.txt"),
        ("5. Livelock prediction", "prediction_results.txt"),
        ("6. Retry strategies under the same fault", "experiment_summary.txt"),
        ("7. Detection applied to the experiment runs", "labeling_experiment.txt"),
    ]
    for title, name in sections:
        parts.append("## " + title + "\n")
        text = read_text(name)
        if text is None:
            if name == "calibration_report.txt":
                parts.append("Optional, and not part of these results. The Alibaba trace has no retry "
                             "or outcome fields, so it can only sanity-check the testbed's latencies and "
                             "call depth. If the trace file is supplied, "
                             "`python calibrate_from_trace.py MSCallGraph_0.tar.gz` does that.\n")
            else:
                parts.append("(missing -- this step did not run)\n")
            continue
        parts.append("```")
        parts.append(text)
        parts.append("```\n")

    parts.append("## Figures\n")
    for path in sorted(glob.glob(os.path.join(FIGURES_DIR, "*.png"))):
        name = os.path.basename(path)
        parts.append("- `figures/%s`" % name)
    parts.append("")

    with open(os.path.join(RESULTS_DIR, "RESULTS.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(parts) + "\n")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--quick", action="store_true",
                        help="small dataset and one repetition, for a live demo")
    parser.add_argument("--keep_data", action="store_true",
                        help="do not wipe old logs first (re-use what is already recorded)")
    parser.add_argument("--n_scenarios", type=int, default=None)
    parser.add_argument("--reps", type=int, default=None)
    parser.add_argument("--seed", type=int, default=7)
    args = parser.parse_args()
    make_dirs()
    if not os.path.exists(LOG_DIR):
        os.makedirs(LOG_DIR)

    n_scenarios = 24
    reps = 5
    experiments = "metastable,error_burst"
    if args.quick:
        n_scenarios = 8
        reps = 1
        experiments = "metastable"
    if args.n_scenarios is not None:
        n_scenarios = args.n_scenarios
    if args.reps is not None:
        reps = args.reps

    for name in SERVICE_PORTS:
        if port_in_use(SERVICE_PORTS[name]):
            print("The services are already running (port %d is busy). This script starts and stops"
                  % SERVICE_PORTS[name])
            print("its own copy, so stop the other one first (Ctrl+C in its terminal).")
            sys.exit(1)

    if not args.keep_data:
        back_up_previous()
        print("wiping old logs and results (use --keep_data to keep them)")
        clean_outputs()

    settings = "%d dataset scenarios (+4 no-fault controls), %d repetition(s) of experiments [%s], seed %d" % (
        n_scenarios, reps, experiments, args.seed)
    print(settings)

    service_log = open(os.path.join(LOG_DIR, "services.log"), "w")
    processes = start_services(DEFAULT_SLOTS, log_file=service_log, verbose=False)
    if processes is None:
        sys.exit(1)
    print("services started")

    started = time.time()
    ok = True
    try:
        steps = [
            ("generate the dataset", ["generate_dataset.py", "--n_scenarios", str(n_scenarios),
                                      "--seed", str(args.seed)]),
            ("label it with the 4 livelock conditions", ["labeling.py", "--group", "dataset", "--sensitivity"]),
            ("train and evaluate the prediction model", ["prediction_model.py"]),
            ("build the time-varying service graph", ["graph_builder.py"]),
            ("run the five-strategy experiments", ["experiment_arms.py", "--reps", str(reps),
                                                   "--experiments", experiments]),
            ("label the experiment runs", ["labeling.py", "--group", "experiment"]),
            ("validate the data", ["validate_data.py"]),
            ("draw the figures", ["make_figures.py"]),
        ]
        number = 1
        for title, script_args in steps:
            if not run_step(number, title, script_args):
                ok = False
                break
            number = number + 1
    except KeyboardInterrupt:
        print("\ninterrupted")
        ok = False
    finally:
        stop_services(processes)
        service_log.close()

    write_results_md(settings)
    print("")
    print("finished in %.1f minutes%s" % ((time.time() - started) / 60.0, "" if ok else " (with errors)"))
    print("all numbers: results/RESULTS.md     figures: results/figures/")
    if not ok:
        sys.exit(1)


if __name__ == "__main__":
    main()
